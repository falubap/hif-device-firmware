"""Write firmware/include/test_vectors.h for the configuration in data/model.json.

    .venv/bin/python python/export_vectors.py --batch 3      # raw windows, batch 3 of the device set
    .venv/bin/python python/export_vectors.py --features-only

Raw windows are 2 x 7 x 2560 float32 (~143 KB each), so only a few fit in the 1 MB of flash: the
device set (DEVICE_VECTORS rows of the test split, fixed seed, stratified by region) is split into
batches of PER_BATCH, one firmware build each.

--features-only writes no windows, only the reference features of EVERY test row, so the model
alone can be checked on the device over the whole test split (Step 3).

Each vector carries the Python reference: features and prediction. With raw windows the reference
features are features.extract on the same float32 window the device gets (data/test_windows);
with --features-only they are the thesis matrix, exactly what scikit-learn was evaluated on.
"""

from __future__ import annotations

import argparse
import json

import joblib
import numpy as np

import features
import paths

HEADER = paths.FIRMWARE_INCLUDE / "test_vectors.h"
DEVICE_VECTORS = 120
N_TEST = 1645           # rows in the test split
PER_BATCH = 6
SEED = 0


def device_rows(y: np.ndarray, n: int = DEVICE_VECTORS) -> np.ndarray:
    """Test-split rows run on the device: n rows, proportional per region, fixed seed, sorted."""
    rng = np.random.default_rng(SEED)
    regions, counts = np.unique(y, return_counts=True)
    quota = np.floor(counts / counts.sum() * n).astype(int)
    quota[np.argsort(-(counts / counts.sum() * n - quota))[: n - quota.sum()]] += 1
    rows = [rng.choice(np.flatnonzero(y == r), q, replace=False) for r, q in zip(regions, quota)]
    return np.sort(np.concatenate(rows))


def batches(n_rows: int = DEVICE_VECTORS, per_batch: int = PER_BATCH) -> int:
    return -(-n_rows // per_batch)


def c_floats(values: np.ndarray) -> str:
    flat = np.asarray(values, dtype=np.float32).ravel()
    return ",".join(f"{float(v):.9e}f" for v in flat)


def write_header(rows, labels, phases, ref_features, ref_preds, x=None, note="", bench=None) -> None:
    """bench: (features, preds) of every test row, for the inference benchmark (Step 6)."""
    k = len(rows)
    nf = ref_features.shape[1]
    lines = [
        "/* Generated by python/export_vectors.py -- do not edit.",
        f" * {note}",
        " */",
        "#ifndef HIF_TEST_VECTORS_H",
        "#define HIF_TEST_VECTORS_H",
        "",
        "#include <stdint.h>",
        "",
        f"#define HIF_TV_COUNT {k}",
        f"#define HIF_TV_HAS_RAW {0 if x is None else 1}",
        f"#define HIF_TV_HAS_BENCH {0 if bench is None else 1}",
        f"#define HIF_TV_N_FEATURES {nf}",
        "",
        "/* Row in the test split, faulted phase (0..2 = A..C), true region, Python's prediction. */",
        f"static const uint16_t hif_tv_index[{k}] = {{{','.join(map(str, rows))}}};",
        f"static const uint8_t hif_tv_phase[{k}] = {{{','.join(map(str, phases))}}};",
        f"static const uint8_t hif_tv_label[{k}] = {{{','.join(map(str, labels))}}};",
        f"static const uint8_t hif_tv_pred[{k}] = {{{','.join(map(str, ref_preds))}}};",
        "",
        "/* Python reference features, model input order. */",
        f"static const float hif_tv_features[{k}][{nf}] = {{{c_floats(ref_features)}}};",
    ]
    if x is not None:
        lines += [
            "",
            f"#define HIF_TV_SAMPLES {features.N}",
            f"#define HIF_TV_CHANNELS {len(features.RAW_CHANNELS)}",
            "/* Raw windows [vector][pre/post][Va Vb Vc Ia Ib Ic In][sample], fs = 15360 Hz. */",
            f"static const float hif_tv_x[{k}][2][{len(features.RAW_CHANNELS)}][{features.N}] = "
            f"{{{c_floats(x)}}};",
        ]
    if bench is not None:
        bf, bp = bench
        lines += [
            "",
            f"#define HIF_BENCH_ROWS {len(bp)}",
            "/* Inference benchmark: reference features and Python's prediction, every test row. */",
            f"static const float hif_bench_features[{len(bp)}][{nf}] = {{{c_floats(bf)}}};",
            f"static const uint8_t hif_bench_pred[{len(bp)}] = {{{','.join(map(str, bp))}}};",
        ]
    lines += ["", "#endif", ""]
    HEADER.write_text("\n".join(lines))


def _load():
    cfg = json.loads((paths.WORK / "model.json").read_text())
    pipe = joblib.load(paths.WORK / "model.joblib")
    w = np.load(paths.TEST_WINDOWS, allow_pickle=True)
    col = {n: i for i, n in enumerate(w["names"].tolist())}
    return cfg, pipe, w, [col[f] for f in cfg["feature_ids"]]


def export_features_only() -> dict:
    """Reference features of every test row, no windows. Returns rows, labels, Python preds."""
    cfg, pipe, w, cols = _load()
    ref = np.load(paths.FEATURES, allow_pickle=True)["X_test"][:, cols].astype(np.float32)
    rows, y = np.arange(len(w["y"])), w["y"]
    preds = pipe.predict(ref)
    write_header(rows, y, w["phase"], ref, preds,
                 note=f"{cfg['description']}; all {len(rows)} test rows, features only")
    return {"rows": rows, "labels": y, "preds": preds, "features": ref}


def export_batch(batch: int, per_batch: int = PER_BATCH) -> dict:
    """One batch of raw windows from the device set. Returns rows, labels, Python preds/features."""
    cfg, pipe, w, cols = _load()
    rows_all = device_rows(w["y"])
    n_batches = batches(len(rows_all), per_batch)
    if not 0 <= batch < n_batches:
        raise ValueError(f"batch must be in 0..{n_batches - 1}")
    rows = rows_all[batch * per_batch : (batch + 1) * per_batch]
    ref = w["feat_f32in"][rows][:, cols].astype(np.float32)
    preds = pipe.predict(ref)
    thesis = np.load(paths.FEATURES, allow_pickle=True)["X_test"][rows][:, cols]
    write_header(rows, w["y"][rows], w["phase"][rows], ref, preds, x=w["x"][rows],
                 note=f"{cfg['description']}; batch {batch} of {n_batches} "
                      f"({len(rows)} of {len(rows_all)} device vectors)")
    # preds: scikit-learn on features.py of the same float32 window (the device's reference);
    # preds_thesis: scikit-learn on the thesis's own features (float64 windows).
    return {"rows": rows, "labels": w["y"][rows], "preds": preds,
            "preds_thesis": pipe.predict(thesis), "features": ref}


def export_bench(per_batch: int, n_rows: int = N_TEST) -> dict:
    """Step 6 benchmark: the first `per_batch` device windows (raw) for extraction, and the
    reference features of `n_rows` test rows (all of them unless flash is short) for inference.
    Returns rows, labels, Python preds for the windows."""
    cfg, pipe, w, cols = _load()
    rows = device_rows(w["y"])[:per_batch]
    ref = w["feat_f32in"][rows][:, cols].astype(np.float32)
    preds = pipe.predict(ref)
    pick = np.sort(np.random.default_rng(SEED).choice(N_TEST, n_rows, replace=False))
    allf = np.load(paths.FEATURES, allow_pickle=True)["X_test"][pick][:, cols].astype(np.float32)
    write_header(rows, w["y"][rows], w["phase"][rows], ref, preds, x=w["x"][rows],
                 bench=(allf, pipe.predict(allf)),
                 note=f"{cfg['description']}; benchmark: {len(rows)} raw windows, "
                      f"{len(allf)} feature rows")
    return {"rows": rows, "labels": w["y"][rows], "preds": preds}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--batch", type=int)
    group.add_argument("--features-only", action="store_true")
    parser.add_argument("--per-batch", type=int, default=PER_BATCH)
    args = parser.parse_args()
    if args.features_only:
        out = export_features_only()
    else:
        out = export_batch(args.batch, args.per_batch)
    print(f"{len(out['rows'])} vectors -> {HEADER}")


if __name__ == "__main__":
    main()

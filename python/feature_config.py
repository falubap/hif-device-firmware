"""Generate firmware/include/feature_config.h: which features the C extractor computes, and how.

For each transform, every derived channel the features use gets a "slot" with the set of orders
(harmonics, or wavelet bands) any feature reads from it; THD reads all 20 harmonics. The C code
computes exactly those and sizes its static buffers from these numbers.
"""

from __future__ import annotations

import features as F
import paths

HEADER = paths.FIRMWARE_INCLUDE / "feature_config.h"

TRANSFORM = {"dft": "HIF_DFT", "stockwell": "HIF_STOCKWELL", "wavelet": "HIF_WAVELET"}
CHANNEL = {
    "fault_voltage": "HIF_CH_FAULT_V", "fault_current": "HIF_CH_FAULT_I",
    "negative_sequence_voltage": "HIF_CH_NEGSEQ_V", "negative_sequence_current": "HIF_CH_NEGSEQ_I",
    "neutral_current": "HIF_CH_NEUTRAL_I", "voltage_sum": "HIF_CH_VSUM",
}
PARAM = {
    "module": "HIF_MODULE", "energy": "HIF_ENERGY", "angle": "HIF_ANGLE", "thd": "HIF_THD",
    "impedance_magnitude": "HIF_IMPEDANCE", "vi_angle": "HIF_VI_ANGLE",
}
STAT = {s: f"HIF_{s.upper()}" for s in
        ("mean", "max", "amplitude", "std", "kurtosis", "entropy", "delta", "ratio")}
ALL_HARMONICS = (1 << F.MAX_ORDER) - 1


def plan(feature_ids: list[str]) -> dict:
    """Slots per transform: {transform: {channel: mask}}, plus each feature's slot indices."""
    slots: dict[str, dict[str, int]] = {t: {} for t in TRANSFORM}
    rows = []
    for fid in feature_ids:
        transform, channels, order, param, stat = F.parse(fid)
        row = F.ORDER_INDEX[order]
        mask = ALL_HARMONICS if param == "thd" else 1 << row
        for ch in channels:
            slots[transform][ch] = slots[transform].get(ch, 0) | mask
        rows.append((transform, channels, row, param, stat))
    index = {t: list(s) for t, s in slots.items()}
    feats = [
        (t, index[t].index(chs[0]), index[t].index(chs[1]) if len(chs) > 1 else 0xFF, row, p, s)
        for t, chs, row, p, s in rows
    ]
    return {"slots": slots, "features": feats}


def write(feature_ids: list[str], description: str) -> None:
    p = plan(feature_ids)
    slots = p["slots"]
    st_orders = 0
    for mask in slots["stockwell"].values():
        st_orders |= mask
    st_max = st_orders.bit_length()
    gauss_len = sum(15 * h + 1 for h in range(1, F.MAX_ORDER + 1) if st_orders >> (h - 1) & 1)
    need_hilbert = any(ch.startswith("negative_sequence") for ch in slots["wavelet"])

    lines = [
        "/* Generated by python/feature_config.py -- do not edit.",
        f" * {description}",
        " */",
        "#ifndef HIF_FEATURE_CONFIG_H",
        "#define HIF_FEATURE_CONFIG_H",
        "",
        '#include "hif_features.h"',
        "",
        f"#define HIF_CFG_N_FEATURES {len(feature_ids)}",
        f"#define HIF_CFG_NEED_HILBERT {int(need_hilbert)}",
        f"#define HIF_CFG_STOCKWELL_MAX_ORDER {st_max}",
        f"#define HIF_CFG_STOCKWELL_GAUSS_LEN {max(gauss_len, 1)}",
    ]
    for t, mask_type in (("dft", "uint32_t"), ("stockwell", "uint32_t"), ("wavelet", "uint16_t")):
        kind = "bands" if t == "wavelet" else "orders"
        chans = list(slots[t])
        lines += ["", f"#define HIF_CFG_{t.upper()}_SLOTS {len(chans)}"]
        if chans:
            lines.append(f"static const uint8_t hif_cfg_{t}_channel[{len(chans)}] = "
                         f"{{{', '.join(CHANNEL[c] for c in chans)}}};")
            lines.append(f"static const {mask_type} hif_cfg_{t}_{kind}[{len(chans)}] = "
                         f"{{{', '.join(hex(slots[t][c]) for c in chans)}}};")
    lines += ["", "/* {transform, slot, slot2, row, parameter, statistic}, model input order. */",
              f"static const hif_feature_t hif_cfg_features[{len(feature_ids)}] = {{"]
    for fid, (t, s1, s2, row, prm, st) in zip(feature_ids, p["features"]):
        lines.append(f"    {{{TRANSFORM[t]}, {s1}, {hex(s2) if s2 == 0xFF else s2}, {row}, "
                     f"{PARAM[prm]}, {STAT[st]}}},  /* {fid} */")
    lines += ["};", "", "#endif", ""]
    HEADER.write_text("\n".join(lines))
